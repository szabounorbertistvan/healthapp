// Links already-cached Open Food Facts products to DishFinder ingredients.
//
// New scans get `foods.dishfinder_ingredient_id` from the barcode-lookup /
// food-search edge functions (supabase/functions/_shared/off-dishfinder.ts). The
// ~840 products cached before that existed carry no categories in our table, so
// this asks OFF for them again (100 codes per request, the same User-Agent the
// functions use) and writes one UPDATE for the ones that map.
//
// Usage (the CLI must be logged in; no DB password needed):
//   supabase db query --linked --project-ref <ref> \
//     "select external_id from public.foods where source = 'off' and dishfinder_ingredient_id is null" \
//     > <scratch>/off-codes.json
//   node --experimental-strip-types scripts/backfill-off-dishfinder.mjs <scratch>/off-codes.json
//   supabase db query --linked --project-ref <ref> -f supabase/seed/off-dishfinder-backfill.sql
//
// The SQL only fills rows that are still null, so it is safe to re-run; the
// mapping itself lives in the shared module, not here. OFF throttles bursts with
// 503s: batches are spaced out and retried with a growing pause. The run ends
// with the most common category tags it could NOT map — the list to grow the
// map from, one honest ingredient at a time.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { dishfinderIdFromOff } from "../supabase/functions/_shared/off-dishfinder.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "supabase/seed/off-dishfinder-backfill.sql");
const input = process.argv[2];
if (!input) {
  console.error("usage: node --experimental-strip-types scripts/backfill-off-dishfinder.mjs <db-query-output.json>");
  process.exit(1);
}

const parsed = JSON.parse(readFileSync(input, "utf8"));
const rows = Array.isArray(parsed) ? parsed : parsed.rows ?? [];
const codes = [...new Set(rows.map((r) => String(r.external_id ?? "").trim()).filter((c) => /^\d{6,14}$/.test(c)))];
console.log(`${codes.length} cached products to look up`);

const UA = "HealthApp/0.1 (relu.plesciuc@sfappworks.com)";
const BATCH = 100;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const linked = [];
const tagFreq = new Map();
let unknown = 0, unmapped = 0;

for (let i = 0; i < codes.length; i += BATCH) {
  const batch = codes.slice(i, i + BATCH);
  const url = `https://world.openfoodfacts.org/api/v2/search?code=${batch.join(",")}&fields=code,product_name,categories_tags&page_size=${BATCH}`;
  let data = null;
  for (let attempt = 1; attempt <= 6 && !data; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (res.ok) data = await res.json();
    else if (res.status === 503 || res.status === 429) await sleep(10000 * attempt);
    else { console.error(`OFF answered ${res.status} for batch ${i / BATCH + 1}`); process.exit(1); }
  }
  if (!data) { console.error(`\nOFF kept refusing batch ${i / BATCH + 1}; re-run later (the SQL fills only what is still null)`); break; }
  const seen = new Set();
  for (const p of data.products ?? []) {
    const code = String(p.code);
    seen.add(code);
    const id = dishfinderIdFromOff(p.categories_tags, p.product_name);
    if (id) linked.push({ code, id });
    else {
      unmapped++;
      const tags = Array.isArray(p.categories_tags) ? p.categories_tags : [];
      const last = tags[tags.length - 1];
      if (typeof last === "string") tagFreq.set(last, (tagFreq.get(last) ?? 0) + 1);
    }
  }
  unknown += batch.filter((c) => !seen.has(c)).length;
  process.stdout.write(`\r  looked up ${Math.min(i + BATCH, codes.length)}/${codes.length} — linked ${linked.length}`);
  await sleep(2000);
}
console.log(`\nlinked ${linked.length}, not an ingredient ${unmapped}, no longer on OFF ${unknown}`);
const top = [...tagFreq.entries()].sort((a, b) => b[1] - a[1]).slice(0, 40);
if (top.length) console.log("most common unmapped (most specific) tags — candidates for the map:\n  " + top.map(([t, n]) => `${t} ×${n}`).join("\n  "));

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`;
const sql = `-- HealthApp · DishFinder ids for Open Food Facts products cached before the
-- category mapping existed (${linked.length} rows). GENERATED by
-- scripts/backfill-off-dishfinder.mjs; mapping in supabase/functions/_shared/off-dishfinder.ts.
-- Fills only rows still null. Safe to re-run.

update public.foods f
   set dishfinder_ingredient_id = v.id
  from (values
${linked.map((l) => `  (${lit(l.code)}, ${l.id})`).join(",\n")}
  ) as v(code, id)
 where f.source = 'off'
   and f.external_id = v.code
   and f.dishfinder_ingredient_id is null;
`;
writeFileSync(output, sql, "utf8");
console.log(`wrote ${path.relative(root, output)}`);
