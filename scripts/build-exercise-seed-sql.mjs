// Turns supabase/seed/exercises.json into supabase/seed/exercises.sql.
//
// The import-exercises edge function does the same upsert, but it only accepts
// the service_role key, which is not available on every dev box. The SQL form
// goes in through the dashboard SQL editor instead — the same path the
// migrations and supabase/seed/accounts.sql already use.
//
// Idempotent: each statement upserts on (source, external_id), so re-running
// after a library update refreshes the system rows and never duplicates them.
// Custom exercises (source = 'custom') are untouched.
//
//   node scripts/build-exercise-seed-sql.mjs

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = path.join(root, "supabase/seed/exercises.json");
const output = path.join(root, "supabase/seed/exercises.sql");

// Rows per INSERT. Small enough that one failing row points at a short
// statement, large enough that the file is not thousands of statements.
const BATCH = 50;

const exercises = JSON.parse(readFileSync(input, "utf8"));

const COLUMNS = [
  "owner_id",
  "source",
  "external_id",
  "name_en",
  "name_ro",
  "category",
  "level",
  "force",
  "mechanic",
  "equipment",
  "primary_muscles",
  "secondary_muscles",
  "instructions_en",
  "images",
];

// Columns the upsert refreshes. name_ro is deliberately excluded: the seed has
// none, and a translation added by hand in the database must survive a re-run.
const UPDATE = COLUMNS.filter((c) => !["owner_id", "source", "external_id", "name_ro"].includes(c));

function lit(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function textArray(values) {
  if (!Array.isArray(values) || values.length === 0) return "'{}'::text[]";
  return `array[${values.map(lit).join(",")}]::text[]`;
}

function row(e) {
  return [
    "null",
    lit("free-exercise-db"),
    lit(e.external_id),
    lit(e.name_en),
    lit(e.name_ro),
    lit(e.category),
    lit(e.level),
    lit(e.force),
    lit(e.mechanic),
    lit(e.equipment),
    textArray(e.primary_muscles),
    textArray(e.secondary_muscles),
    lit(e.instructions_en),
    textArray(e.images),
  ].join(", ");
}

const statements = [];
for (let i = 0; i < exercises.length; i += BATCH) {
  const chunk = exercises.slice(i, i + BATCH);
  statements.push(
    `insert into public.exercises (${COLUMNS.join(", ")}) values\n` +
      chunk.map((e) => `  (${row(e)})`).join(",\n") +
      `\non conflict (source, external_id) do update set\n` +
      UPDATE.map((c) => `  ${c} = excluded.${c}`).join(",\n") +
      `,\n  updated_at = now();`,
  );
}

const header = `-- HealthApp · system exercise library (${exercises.length} rows)
--
-- GENERATED by scripts/build-exercise-seed-sql.mjs from supabase/seed/exercises.json.
-- Do not edit by hand; edit the JSON (or re-import) and regenerate.
--
-- Paste into the Supabase dashboard → SQL Editor → Run. Safe to re-run: rows
-- upsert on (source, external_id). Existing name_ro translations are kept.
--
-- Source: Free Exercise DB (public domain, https://github.com/yuhonas/free-exercise-db).
-- Images hot-link to that repository's raw GitHub URLs.

`;

writeFileSync(output, header + statements.join("\n\n") + "\n", "utf8");
console.log(`wrote ${path.relative(root, output)}: ${exercises.length} rows in ${statements.length} statements`);
